## Generators: type-inferred and combinators.

import std/[unittest, sets, math, strutils, sequtils]
import proptest

type
  Color = enum red, green, blue
  Small = range[-3 .. 7]
  Account = object
    id: int
    owner: string

proc arbitrary(src: ChoiceSource; t: typedesc[Account]): Account =
  ## A user-defined generator: ids are positive, owners are lowercase.
  Account(id: src.drawInt(1, 1_000_000),
          owner: strings("abcdefghijklmnopqrstuvwxyz", 1, 8).generate(src))

suite "type-inferred generators":
  test "G2/G3: every built-in type is generated by forAll":
    var cases = 0
    var colors: HashSet[Color]
    forAll(initSettings(seed = 11, cases = 300),
           a in int8, b in uint64, c in float, d in char, e in string, f in Color,
           g in Option[int], h in array[3, bool], i in (int, string), j in set[char],
           k in Small, l in seq[seq[uint8]], m in float32, n in bool):
      inc cases
      colors.incl f
      check k >= -3 and k <= 7
    check cases == 300
    check colors == toHashSet([red, green, blue])

  test "G2/G8: integer extremes are reached while exploring":
    var seen: HashSet[int8]
    forAll(initSettings(seed = 12, cases = 500), x in int8):
      seen.incl x
    check low(int8) in seen
    check high(int8) in seen
    check 0'i8 in seen

  test "G3/C7: user overloads of arbitrary are used by forAll":
    forAll(initSettings(seed = 13), acc in Account):
      check acc.id >= 1
      check acc.owner.len in 1 .. 8
      check acc.owner.allCharsInSet({'a' .. 'z'})

  test "RL15/Q7: golden values for a fixed seed":
    # Changing what a seed generates is a breaking change (RL15): if this
    # test fails, update it only together with a CHANGELOG entry.
    let src = newChoiceSource(42)
    src.startRandom(50)
    check show(src.arbitrary(seq[int])) == "@[-6, -12, -9223372036854775808, 2, " &
      "-3667718038, -8, 76221, -1, 5, -1227701246, -19, -91576, 9223372036854775807, " &
      "-46, -9223372036854775808, -9223372036854775808, -42, -8429, 1, 28, -1, -1810, " &
      "-9223372036854775808, 39, 3200791, 0, -1, 118992042, -11, -8, -33, 1, 3843928]"
    check src.arbitrary(string) == "1_0/+sfEIl,"
    check src.arbitrary(int8) == 1
    check src.arbitrary(uint16) == 10
    check src.arbitrary(Color) == green
    check src.arbitrary(Option[int]) == some(-2)
    check src.arbitrary((bool, char)) == (true, '\x8C')
    check src.arbitrary(float) == 0.8021383285522461
    check src.choiceCount == 137

suite "combinators":
  test "C1: map transforms values":
    forAll(initSettings(seed = 21), s in ints(0, 100).map(proc(x: int): string = $x)):
      check s.parseInt in 0 .. 100

  test "C1: filter keeps only accepted values":
    let evens = ints(0, 10_000).filter(proc(x: int): bool = x mod 2 == 0)
    forAll(initSettings(seed = 22), n in evens):
      check n mod 2 == 0

  test "C1: flatMap makes a generator depend on a value":
    let sized = ints(1, 10).flatMap(proc(n: int): Gen[seq[int]] = seqs(ints(0, 9), n, n))
    forAll(initSettings(seed = 23), xs in sized):
      check xs.len in 1 .. 10
      check xs.allIt(it in 0 .. 9)

  test "C2: oneOf, elements and constant":
    var seen: HashSet[int]
    forAll(initSettings(seed = 24), x in oneOf(constant(1), constant(2), elements([3, 4]))):
      seen.incl x
    check seen == toHashSet([1, 2, 3, 4])

  test "G6/G9: strings, chars, floats and seqs honour their parameters":
    forAll(initSettings(seed = 25),
           s in strings("ab", 1, 3), c in chars("xyz"), f in floats(-1.0, 1.0),
           g in floats(allowNaN = false, allowInf = false), xs in seqs(bools(), 2, 2),
           o in optionals(ints(5, 6))):
      check s.len in 1 .. 3 and s.allCharsInSet({'a', 'b'})
      check c in {'x', 'y', 'z'}
      check f >= -1.0 and f <= 1.0
      check not g.isNaN and g.classify notin {fcInf, fcNegInf}
      check xs.len == 2
      check o.isNone or o.get in 5 .. 6

  test "C1/C2/G9: invalid generator arguments raise ValueError":
    expect ValueError: discard ints(5, 1)
    expect ValueError: discard elements(newSeq[int]())
    expect ValueError: discard oneOf(newSeq[Gen[int]]())
    expect ValueError: discard strings(minLen = 3, maxLen = 1)
    expect ValueError: discard floats(1.0, 0.0)
    expect ValueError: discard chars("")
    expect ValueError: discard seqs(bools(), -1)
