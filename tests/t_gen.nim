## Generators: type-inferred and combinators.

import std/[unittest, sets, math, strutils, sequtils, algorithm]
import proptest

type
  Color = enum red, green, blue
  Small = range[-3 .. 7]
  Account = object
    id: int
    owner: string

proc arbitrary(src: ChoiceSource; t: typedesc[Account]): Account =
  ## A user-defined generator: ids are positive, owners are lowercase.
  Account(id: src.drawInt(1, 1_000_000),
          owner: strings("abcdefghijklmnopqrstuvwxyz", 1, 8).generate(src))

suite "type-inferred generators":
  test "G2/G3: every built-in type is generated by forAll":
    var cases = 0
    var colors: HashSet[Color]
    forAll(initSettings(seed = 11, cases = 300, suppress = {hcLargeData}),
           a in int8, b in uint64, c in float, d in char, e in string, f in Color,
           g in Option[int], h in array[3, bool], i in (int, string), j in set[char],
           k in Small, l in seq[seq[uint8]], m in float32, n in bool):
      inc cases
      colors.incl f
      check k >= -3 and k <= 7
    check cases == 300
    check colors == toHashSet([red, green, blue])

  test "G2/G8: integer extremes are reached while exploring":
    var seen: HashSet[int8]
    forAll(initSettings(seed = 12, cases = 500), x in int8):
      seen.incl x
    check low(int8) in seen
    check high(int8) in seen
    check 0'i8 in seen

  test "G3/C7: user overloads of arbitrary are used by forAll":
    forAll(initSettings(seed = 13), acc in Account):
      check acc.id >= 1
      check acc.owner.len in 1 .. 8
      check acc.owner.allCharsInSet({'a' .. 'z'})

  test "RL15/Q7: golden values for a fixed seed":
    # Changing what a seed generates is a generation change (RL15,
    # docs/STABILITY.md): if this test fails, update it only together with a
    # CHANGELOG entry under "Generation changes". t_golden covers the whole
    # pipeline; this test pins the primitives directly.
    let src = newChoiceSource(42)
    src.startRandom(50)
    # Values changed in v0.3 (edge bias, ADR-0012) and in the generation
    # changes after v0.4 (one zigzag choice per signed integer): see the
    # CHANGELOG.
    check show(src.arbitrary(seq[int])) == "@[-2, -24728120, -18, -9223372036854775808, " &
      "-56605757, 0, 1902, -3, 0, -963016698, -36950, -717, -9223372036854775808, -50, 693, " &
      "4545, 1, -9, 78, 9223372036854775807, 13, -20, -17, 9223372036854775807, 1, 0, " &
      "-481264914, -11, 0, -92933, 805087730, 0, -110659]"
    check src.arbitrary(string) == ""
    check src.arbitrary(int8) == -14
    check src.arbitrary(uint16) == 54623
    check src.arbitrary(Color) == green
    check src.arbitrary(Option[int]) == some(-19)
    check src.arbitrary((bool, char)) == (true, '\xA9')
    check $src.arbitrary(float) == "0.0"
    check src.choiceCount == 80

suite "combinators":
  test "C1: map transforms values":
    forAll(initSettings(seed = 21), s in ints(0, 100).map(proc(x: int): string = $x)):
      check s.parseInt in 0 .. 100

  test "C1: filter keeps only accepted values":
    let evens = ints(0, 10_000).filter(proc(x: int): bool = x mod 2 == 0)
    forAll(initSettings(seed = 22), n in evens):
      check n mod 2 == 0

  test "C1: flatMap makes a generator depend on a value":
    let sized = ints(1, 10).flatMap(proc(n: int): Gen[seq[int]] = seqs(ints(0, 9), n, n))
    forAll(initSettings(seed = 23), xs in sized):
      check xs.len in 1 .. 10
      check xs.allIt(it in 0 .. 9)

  test "C2: oneOf, elements and constant":
    var seen: HashSet[int]
    forAll(initSettings(seed = 24, suppress = {hcFewDistinct}),
           x in oneOf(constant(1), constant(2), elements([3, 4]))):
      seen.incl x
    check seen == toHashSet([1, 2, 3, 4])

  test "G6/G9: strings, chars, floats and seqs honour their parameters":
    forAll(initSettings(seed = 25),
           s in strings("ab", 1, 3), c in chars("xyz"), f in floats(-1.0, 1.0),
           g in floats(allowNaN = false, allowInf = false), xs in seqs(bools(), 2, 2),
           o in optionals(ints(5, 6))):
      check s.len in 1 .. 3 and s.allCharsInSet({'a', 'b'})
      check c in {'x', 'y', 'z'}
      check f >= -1.0 and f <= 1.0
      check not g.isNaN and g.classify notin {fcInf, fcNegInf}
      check xs.len == 2
      check o.isNone or o.get in 5 .. 6

  test "C1/C2/G9: invalid generator arguments raise ValueError":
    expect ValueError: discard ints(5, 1)
    expect ValueError: discard elements(newSeq[int]())
    expect ValueError: discard oneOf(newSeq[Gen[int]]())
    expect ValueError: discard strings(minLen = 3, maxLen = 1)
    expect ValueError: discard floats(1.0, 0.0)
    expect ValueError: discard chars("")
    expect ValueError: discard seqs(bools(), -1)

suite "size and collection shapes (C5, C6)":
  test "C5: sized sees the size, which grows over the run":
    var sizes: seq[int]
    let g = sized(proc(n: int): Gen[int] = constant(n))
    forAll(initSettings(seed = 31, cases = 50, maxSize = 49), n in g):
      sizes.add n
    check sizes[0] == 0
    check sizes[^1] == 49
    check sizes == sizes.sorted

  test "V-C5: a sized failure shrinks to the smallest failing size and replays":
    let g = sized(proc(n: int): Gen[seq[int]] = seqs(ints(0, 9), n, n))
    let r = forAllResult(initSettings(seed = 32), xs in g):
      check xs.len < 30
    check r.status == psFailed          # not flaky: the size is replayed
    check r.failures[0].inputs[0].value == "@[" & repeat("0", 30).join(", ") & "]"

  test "C5: resize fixes the size of a generator":
    var longest = 0
    forAll(initSettings(seed = 33), xs in gen(seq[int]).resize(2)):
      longest = max(longest, xs.len)
    check longest <= 5
    expect ValueError:
      discard gen(int).resize(-1)

  test "C6: uniqueSeqs gives distinct values and shrinks to small distinct ones":
    forAll(initSettings(seed = 34), xs in uniqueSeqs(ints(0, 50), maxLen = 20)):
      check xs.toHashSet.len == xs.len
    let r = forAllResult(initSettings(seed = 35), xs in uniqueSeqs(ints(0, 1000))):
      check xs.len < 4
    let shrunk = r.failures[0].inputs[0].value
    check shrunk.count(',') == 3                    # exactly 4 elements
    for c in shrunk: check c notin {'4' .. '9'}     # all of them small

  test "C6: uniqueSeqs over too few distinct values gives up and says why":
    let r = forAllResult(initSettings(seed = 36), xs in uniqueSeqs(bools(), minLen = 3)):
      discard
    check r.status == psGaveUp
    check "uniqueSeqs" in r.message

  test "C6: sortedSeqs are in order and shrink like seqs":
    let r = forAllResult(initSettings(seed = 37), xs in sortedSeqs(ints(-100, 100))):
      check xs.isSorted
      check xs.len < 3 or xs[^1] < 50
    check r.status == psFailed
    check r.failures[0].inputs[0].value == "@[0, 0, 50]"
    expect ValueError:
      discard sortedSeqs(ints(), 3, 1)
