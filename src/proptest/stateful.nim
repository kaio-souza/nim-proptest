## Stateful (model-based) testing (ADR-0011).
##
## `stateMachine` describes a model, a system under test built fresh for each
## sequence, and commands. The macro generates, at module level:
##
## - `<Name>`: a marker type naming the machine;
## - `<Name>Step` / `<Name>StepKind`: one step as a value (command + arguments);
## - one constructor per command, overloaded on the marker type
##   (`push(BoundedQueue, 3)`), used by `replayCommands`;
## - `stateMachineRunner(<Name>)`: a closure that runs one sequence, either
##   generated from a `ChoiceSource` or replayed from given steps.
##
## The commands are inlined in a single `case` inside that closure: no
## dynamic dispatch, and argument generators that do not read the model or
## the system are built once per property, not per step.

import std/[macros, os, strutils]
import choices, gen, assertions, engine, labels, mining, prng

type
  StateRunner*[S] = proc(src: ChoiceSource; steps: seq[S]; replay: bool;
                         maxSteps: int; swarm: bool) {.closure.}
    ## Runs one sequence. Generated by `stateMachine`; see `stateMachineRunner`.
    ## In replay mode `src` is not used and may be nil.

proc raisePrecondition*(index: int; step: string) {.noinline.} =
  raise newException(ValueError, "replayCommands: precondition of step " & $index &
    " (" & step & ") is false, so this sequence cannot happen")

proc runStateMachine*[S](runner: StateRunner[S]; settings: Settings;
                         machine: string; dbKey = ""): PropertyResult =
  ## Runs random command sequences with the engine of `forAll`.
  var s = settings
  let key = if s.name.len > 0: s.name else: dbKey
  if s.name.len == 0: s.name = machine
  let maxSteps = s.maxSteps
  let swarm = s.swarm
  let noSteps: seq[S] = @[]
  let prop: PropertyProc = proc(src: ChoiceSource) =
    runner(src, noSteps, false, maxSteps, swarm)
  result = runProperty(prop, s, key)
  # Commands that never ran: the model was never exercised there (O4).
  for st in result.labels:
    if st.kind == lkCommand and st.cases == 0 and result.labeledCases > 0:
      var line = "command '" & st.name & "' never ran in " & $result.labeledCases & " sequences"
      for d in result.labels:
        if d.kind == lkDisabled and d.name == st.name:
          line.add "; its precondition was false " & $d.events & " times"
      result.warnings.add line

proc replaySteps*[S](runner: StateRunner[S]; steps: seq[S]) =
  ## Runs `steps` in order with the machine's setup, preconditions,
  ## postconditions, invariants and teardown. Raises on the first failure.
  # No ChoiceSource in replay mode (the runner never touches it): ARC in
  # Nim 2.2.4 leaks a ref created here when the runner raises.
  runner(nil, steps, true, steps.len, false)

# ------------------------------------------------------------------- parsing

type
  Arg = object
    name, source: NimNode
    hoisted: bool

  Command = object
    name: NimNode
    args: seq[Arg]
    precondition, run, postcondition, update: NimNode

  Machine = object
    name, model: NimNode
    setup, teardown, invariant: NimNode
    commands: seq[Command]

proc sectionName(n: NimNode): string =
  ## `name: body` parses as a call of `name` with a statement list.
  if n.kind in {nnkCall, nnkCommand} and n.len == 2 and n[0].kind == nnkIdent and
     n[1].kind == nnkStmtList:
    result = $n[0]

proc mentions(n: NimNode; names: openArray[string]): bool =
  if n.kind == nnkIdent:
    for x in names:
      if n.eqIdent(x): return true
  for c in n:
    if mentions(c, names): return true

proc declaredNames(setup: NimNode): seq[string] =
  for s in setup:
    if s.kind in {nnkLetSection, nnkVarSection, nnkConstSection}:
      for d in s:
        for i in 0 ..< d.len - 2:
          var n = d[i]
          if n.kind == nnkPragmaExpr: n = n[0]
          if n.kind == nnkPostfix: n = n[1]
          if n.kind == nnkIdent: result.add $n

proc parseCommand(n: NimNode; stateNames: seq[string]): Command =
  let sig = n[1]
  if sig.kind == nnkObjConstr:
    # `put(x: int)`: every argument `name: T` makes Nim parse an object
    # constructor (see ADR-0010).
    error("declare command arguments as `name in Type` or `name in generator`", sig)
  if sig.kind notin {nnkCall, nnkIdent} or n.len != 3 or n[2].kind != nnkStmtList:
    error("expected `command name(x in source, ...):` followed by its sections", n)
  if sig.kind == nnkIdent:
    result.name = sig
  else:
    result.name = sig[0]
    for i in 1 ..< sig.len:
      let a = sig[i]
      if not (a.kind == nnkInfix and a[0].eqIdent("in") and a[1].kind == nnkIdent):
        error("declare command arguments as `name in Type` or `name in generator`", a)
      result.args.add Arg(name: a[1], source: a[2],
                          hoisted: not mentions(a[2], stateNames))
  if result.name.kind != nnkIdent:
    error("a command name must be an identifier", result.name)
  for s in n[2]:
    case sectionName(s)
    of "precondition": result.precondition = s[1]
    of "run": result.run = s[1]
    of "postcondition": result.postcondition = s[1]
    of "update": result.update = s[1]
    else:
      error("unknown command section; expected precondition:, run:, postcondition: " &
            "or update:", s)
  if result.run.isNil:
    error("command '" & $result.name & "' needs a `run:` section", n)

proc parseMachine(name, body: NimNode): Machine =
  if name.kind != nnkIdent:
    error("expected `stateMachine Name:`", name)
  result.name = name
  result.setup = newStmtList()
  result.teardown = newStmtList()
  result.invariant = newStmtList()
  var commandNodes: seq[NimNode]
  for s in body:
    if s.kind == nnkCommand and s.len >= 2 and s[0].eqIdent("command"):
      commandNodes.add s
      continue
    case sectionName(s)
    of "model": result.model = s[1]
    of "setup":
      for c in s[1]: result.setup.add c
    of "teardown":
      for c in s[1]: result.teardown.add c
    of "invariant":
      for c in s[1]: result.invariant.add c
    else:
      if s.kind == nnkCommentStmt: continue
      error("unknown stateMachine section; expected model:, setup:, teardown:, " &
            "invariant: or command name(...):", s)
  if result.model.isNil:
    error("stateMachine needs a `model:` section (use `model: ()` when there is none)", body)
  if commandNodes.len == 0:
    error("stateMachine needs at least one command", body)
  if commandNodes.len > 255:
    error("stateMachine supports at most 255 commands", body)
  let stateNames = @["model"] & declaredNames(result.setup)
  for c in commandNodes:
    let cmd = parseCommand(c, stateNames)
    for other in result.commands:
      if other.name.eqIdent(cmd.name):
        error("duplicate command '" & $cmd.name & "'", c)
    result.commands.add cmd

# ---------------------------------------------------------------- generation

proc asChecks(body, propCheckSym: NimNode): NimNode =
  ## A single expression is a condition to check; anything else is code
  ## whose `check`/`require` are rewritten (ADR-0009).
  if body.len == 1:
    let s = body[0]
    let isAssertCall = s.kind in {nnkCall, nnkCommand} and s.len >= 1 and
      s[0].kind == nnkIdent and
      (s[0].eqIdent("check") or s[0].eqIdent("require") or
       s[0].eqIdent("doAssert") or s[0].eqIdent("assert"))
    # Calls to bound symbols come from our own rewrites (labels): statements.
    let ownCall = s.kind == nnkCall and s.len >= 1 and s[0].kind in {nnkSym, nnkClosedSymChoice}
    if not isAssertCall and not ownCall and s.kind in {nnkInfix, nnkPrefix, nnkIdent, nnkDotExpr,
                                       nnkPar, nnkCall, nnkCommand}:
      return newStmtList(newCall(propCheckSym, s))
  rewriteChecks(body, propCheckSym)

proc field(cmd: Command; i: int): NimNode =
  ident($cmd.name & "Arg" & $i)

proc used(n: NimNode): NimNode =
  nnkPragmaExpr.newTree(n, nnkPragma.newTree(ident"used"))

macro stateMachine*(name, body: untyped): untyped =
  ## Defines a state machine at module level; see ADR-0011 and the stateful
  ## testing tutorial.
  let m = parseMachine(name, body)
  let mName = $m.name
  let stepT = ident(mName & "Step")
  let kindT = ident(mName & "StepKind")
  let modelId = ident"model"
  let propCheckSym = bindSym"propCheck"
  result = newStmtList()

  # Argument types: what the source draws, with model and setup in scope.
  proc argType(a: Arg): NimNode =
    let blk = newStmtList(
      nnkVarSection.newTree(newIdentDefs(used(modelId), newEmptyNode(), m.model)),
      m.setup.copyNimTree,
      newCall(bindSym"drawFrom", newCall(ident"default", ident"ChoiceSource"),
              newCall(bindSym"hoist", a.source.copyNimTree)))
    newCall(ident"typeof", nnkPar.newTree(nnkBlockStmt.newTree(newEmptyNode(), blk)))

  # Each argument type gets a concrete alias: a `typeof` used directly as a
  # parameter type stays unresolved during overload resolution.
  var aliases = nnkTypeSection.newTree()
  var argTypes: seq[seq[NimNode]]
  for cmd in m.commands:
    var row: seq[NimNode]
    for i, a in cmd.args:
      let t = genSym(nskType, mName & "_" & $cmd.name & "_" & $i)
      aliases.add nnkTypeDef.newTree(t, newEmptyNode(), argType(a))
      row.add t
    argTypes.add row
  if aliases.len > 0: result.add aliases

  # type <Name>* = object; <Name>StepKind* {.pure.} = enum ...; <Name>Step* = object ...
  var kinds = nnkEnumTy.newTree(newEmptyNode())
  var recCase = nnkRecCase.newTree(newIdentDefs(postfix(ident"kind", "*"), kindT))
  for ci, cmd in m.commands:
    kinds.add cmd.name
    var fields = nnkRecList.newTree()
    for i, a in cmd.args:
      fields.add newIdentDefs(postfix(field(cmd, i), "*"), argTypes[ci][i])
    if fields.len == 0: fields.add newNilLit()
    recCase.add nnkOfBranch.newTree(newDotExpr(kindT, cmd.name), fields)
  result.add nnkTypeSection.newTree(
    nnkTypeDef.newTree(postfix(m.name, "*"), newEmptyNode(),
      nnkObjectTy.newTree(newEmptyNode(), newEmptyNode(), newEmptyNode())),
    nnkTypeDef.newTree(
      nnkPragmaExpr.newTree(postfix(kindT, "*"), nnkPragma.newTree(ident"pure")),
      newEmptyNode(), kinds),
    nnkTypeDef.newTree(postfix(stepT, "*"), newEmptyNode(),
      nnkObjectTy.newTree(newEmptyNode(), newEmptyNode(), nnkRecList.newTree(recCase))))

  # Constructors: proc push*(_: typedesc[M]; x: T): MStep
  for ci, cmd in m.commands:
    var params = @[stepT, newIdentDefs(ident"_", nnkBracketExpr.newTree(ident"typedesc", m.name))]
    var ctor = nnkObjConstr.newTree(stepT, newColonExpr(ident"kind", newDotExpr(kindT, cmd.name)))
    for i, a in cmd.args:
      params.add newIdentDefs(a.name, argTypes[ci][i])
      ctor.add newColonExpr(field(cmd, i), a.name)
    result.add newProc(postfix(cmd.name, "*"), params, newStmtList(ctor))

  # Failure database key (ADR-0014): machine name, file and a hash of its code.
  let keyLit = newLit(mName & "@" & extractFilename(name.lineInfoObj.filename) & "#" &
                      toHex(fnv1a64(body.repr)))
  result.add newProc(postfix(ident"stateMachineKey", "*"),
    [ident"string", newIdentDefs(ident"_", nnkBracketExpr.newTree(ident"typedesc", m.name))],
    newStmtList(keyLit))

  # `$` of a step as a Nim call: push(3)
  let stepVar = ident"step"
  var codeCase = nnkCaseStmt.newTree(newDotExpr(stepVar, ident"kind"))
  for cmd in m.commands:
    var e = newLit($cmd.name & "(")
    for i in 0 ..< cmd.args.len:
      if i > 0: e = infix(e, "&", newLit(", "))
      e = infix(e, "&", newCall(bindSym"showCode", newDotExpr(stepVar, field(cmd, i))))
    e = infix(e, "&", newLit(")"))
    codeCase.add nnkOfBranch.newTree(newDotExpr(kindT, cmd.name), newStmtList(e))
  result.add newProc(postfix(ident"stepCode", "*"),
    [ident"string", newIdentDefs(stepVar, stepT)], newStmtList(codeCase))

  # The runner.
  let src = genSym(nskParam, "src")
  let steps = genSym(nskParam, "steps")
  let replay = genSym(nskParam, "replay")
  let maxSteps = genSym(nskParam, "maxSteps")
  let swarm = genSym(nskParam, "swarm")
  let many = genSym(nskVar, "many")
  let idx = genSym(nskVar, "idx")
  let enabled = genSym(nskVar, "enabled")
  let n = genSym(nskVar, "n")
  let ok = genSym(nskVar, "ok")
  let cur = genSym(nskVar, "cur")
  var hoists = newStmtList()
  var hoistSyms: seq[seq[NimNode]]
  for cmd in m.commands:
    var row: seq[NimNode]
    for a in cmd.args:
      if a.hoisted:
        let g = genSym(nskLet, $cmd.name & "_" & $a.name)
        hoists.add newLetStmt(g, newCall(bindSym"hoist", a.source))
        row.add g
      else:
        row.add nil
    hoistSyms.add row

  let nCmd = m.commands.len
  var slot = 2 * nCmd          # user labels after commands and disabled counts
  let allowed = genSym(nskVar, "allowed")
  let enabledAll = genSym(nskVar, "enabledAll")
  let nAll = genSym(nskVar, "nAll")
  var registerAll = newStmtList()
  var enable = newStmtList()
  var drawCase = nnkCaseStmt.newTree(nnkBracketExpr.newTree(enabled,
    newCall(bindSym"drawIndex", src, n)))
  var execCase = nnkCaseStmt.newTree(newDotExpr(cur, ident"kind"))
  for ci, cmd in m.commands:
    let kindVal = newDotExpr(kindT, cmd.name)
    let pre = if cmd.precondition.isNil: newLit(true) else: cmd.precondition
    let ciLit = newLit(ci)
    let disabledSlot = newLit(nCmd + ci)
    let cmdName = newLit($cmd.name)
    registerAll.add quote do:
      recordLabel(`src`, `ciLit`, false, `cmdName`, lkCommand)
    enable.add quote do:
      if `pre`:
        `enabledAll`[`nAll`] = `kindVal`
        inc `nAll`
        if `allowed`[`ciLit`]:
          `enabled`[`n`] = `kindVal`
          inc `n`
      elif not `replay`:
        recordLabel(`src`, `disabledSlot`, true, `cmdName`, lkDisabled)
    # Draw the arguments, then build the step.
    var draw = newStmtList()
    var ctor = nnkObjConstr.newTree(stepT, newColonExpr(ident"kind", kindVal))
    for i, a in cmd.args:
      let v = genSym(nskLet, $a.name)
      let g = if hoistSyms[ci][i] != nil: hoistSyms[ci][i]
              else: newCall(bindSym"hoist", a.source)
      draw.add newLetStmt(v, newCall(bindSym"drawFrom", src, g))
      ctor.add newColonExpr(field(cmd, i), v)
    draw.add newAssignment(cur, ctor)
    draw.add newCall(bindSym"recordLabel", src, newLit(ci), newLit(true), newLit($cmd.name),
                     bindSym"lkCommand")
    drawCase.add nnkOfBranch.newTree(kindVal, draw)
    # Execute it.
    var exec = newStmtList()
    for i, a in cmd.args:
      exec.add nnkLetSection.newTree(newIdentDefs(used(a.name), newEmptyNode(),
        newDotExpr(cur, field(cmd, i))))
    let run = rewriteChecks(rewriteLabels(cmd.run, src, slot), propCheckSym)
    if cmd.postcondition.isNil:
      exec.add run
    else:
      var value = newNimNode(nnkStmtListExpr)
      for c in run: value.add c
      # `result` names the value of `run:` (ADR-0011); the runner is a void
      # closure, so nothing real is shadowed.
      exec.add nnkPragma.newTree(ident"push",
        nnkExprColonExpr.newTree(nnkBracketExpr.newTree(ident"warning", ident"ResultShadowed"),
                                 ident"off"))
      exec.add nnkLetSection.newTree(newIdentDefs(used(ident"result"), newEmptyNode(), value))
      exec.add nnkPragma.newTree(ident"pop")
      exec.add asChecks(rewriteLabels(cmd.postcondition, src, slot), propCheckSym)
    if not cmd.update.isNil:
      exec.add rewriteChecks(rewriteLabels(cmd.update, src, slot), propCheckSym)
    execCase.add nnkOfBranch.newTree(kindVal, newBlockStmt(exec))

  let invariant = if m.invariant.len == 0: newStmtList()
                  else: asChecks(rewriteLabels(m.invariant, src, slot), propCheckSym)
  let teardown = if m.teardown.len == 0: newStmtList(nnkDiscardStmt.newTree(newEmptyNode()))
                 else: rewriteChecks(m.teardown, propCheckSym)
  let setup = rewriteChecks(m.setup, propCheckSym)
  let modelExpr = m.model
  let nameLit = newLit(mName)
  let mined = genSym(nskLet, "hints")
  let bodyAcc = genSym(nskVar, "bodyHints")
  hoists.add bodyHints(body, bodyAcc)
  let fileHints = genSym(nskLet, "fileHints")
  hoists.add newLetStmt(mined, bodyAcc)
  hoists.add newLetStmt(fileHints, prefix(minedHints(name), "@"))
  let nCommands = newLit(m.commands.len)
  let modelDecl = nnkVarSection.newTree(newIdentDefs(used(modelId), newEmptyNode(), modelExpr))
  let stepCodeId = ident"stepCode"

  let body = quote do:
    if not `replay`:
      beginBody(`src`)
      if `src`.recordInputs: `src`.machine = `nameLit`
    `modelDecl`
    `setup`
    var `idx` = 0
    try:
      var `many` = if `replay`: Many() else: initMany(`src`, 0, `maxSteps`)
      # Swarm testing (ADR-0012): each sequence may leave some commands out,
      # so long runs of the others become likely. Choice 0 = allowed.
      var `allowed`: array[`nCommands`, bool]
      for i in 0 ..< `nCommands`:
        `allowed`[i] = true
      if not `replay`:
        useHints(`src`, `mined`, `fileHints`)
        `registerAll`
        # Half of the sequences (choice 1) leave out each command with
        # probability 1/2; the other half keep every command. Shrinking
        # moves toward "no swarm".
        if `swarm` and `nCommands` > 1 and drawBool(`src`):
          for i in 0 ..< `nCommands`:
            `allowed`[i] = not drawBool(`src`)
      while true:
        var `enabled`: array[`nCommands`, `kindT`]
        var `enabledAll`: array[`nCommands`, `kindT`]
        var `n` = 0
        var `nAll` = 0
        `enable`
        if `n` == 0:   # the swarm left nothing: every enabled command
          `enabled` = `enabledAll`
          `n` = `nAll`
        var `cur`: `stepT`
        if `replay`:
          if `idx` >= `steps`.len: break
          `cur` = `steps`[`idx`]
          var `ok` = false
          for j in 0 ..< `n`:
            if `enabled`[j] == `cur`.kind: `ok` = true
          if not `ok`: raisePrecondition(`idx` + 1, `stepCodeId`(`cur`))
        else:
          if `n` == 0: break
          if not more(`src`, `many`): break
          beginGenerate(`src`)
          `drawCase`
          beginBody(`src`)
          if `src`.recordInputs: `src`.steps.add `stepCodeId`(`cur`)
        `execCase`
        `invariant`
        if not `replay`: endElement(`src`, `many`)
        inc `idx`
    finally:
      if not `replay`: recordLength(`src`, `idx`)
      `teardown`

  let runnerProc = newProc(newEmptyNode(),
    [newEmptyNode(), newIdentDefs(src, bindSym"ChoiceSource"),
     newIdentDefs(steps, nnkBracketExpr.newTree(ident"seq", stepT)),
     newIdentDefs(replay, ident"bool"), newIdentDefs(maxSteps, ident"int"),
     newIdentDefs(swarm, ident"bool")],
    body, nnkLambda)
  let runnerT = nnkBracketExpr.newTree(bindSym"StateRunner", stepT)
  result.add newProc(postfix(ident"stateMachineRunner", "*"),
    [runnerT, newIdentDefs(ident"_", nnkBracketExpr.newTree(ident"typedesc", m.name))],
    newStmtList(hoists, newAssignment(ident"result", runnerProc)))

macro replayCommands*(machine, body: untyped): untyped =
  ## Runs the given steps, as printed in a stateful failure report (M4):
  ##
  ## .. code-block:: nim
  ##   replayCommands BoundedQueue:
  ##     push(0)
  ##     pop()
  let stepT = ident($machine & "Step")
  let steps = genSym(nskVar, "steps")
  result = newStmtList(nnkVarSection.newTree(newIdentDefs(steps,
    nnkBracketExpr.newTree(ident"seq", stepT))))
  for s in body:
    case s.kind
    of nnkCall, nnkCommand:
      var c = newCall(s[0], machine)
      for i in 1 ..< s.len: c.add s[i]
      result.add newCall(newDotExpr(steps, ident"add"), c)
    of nnkIdent:
      result.add newCall(newDotExpr(steps, ident"add"), newCall(s, machine))
    of nnkDiscardStmt, nnkCommentStmt:
      discard
    else:
      error("replayCommands expects one command call per line, e.g. `push(0)`", s)
  # Named locals only: ARC (Nim 2.2.4) leaks temporaries passed to a call
  # that raises, and a failing replay raises.
  let runner = genSym(nskLet, "runner")
  result.add newLetStmt(runner, newCall(ident"stateMachineRunner", machine))
  result.add newCall(bindSym"replaySteps", runner, steps)
  result = newBlockStmt(result)

template stateMachineResult*(machine: typedesc; settings: Settings = initSettings()): PropertyResult =
  ## Runs random command sequences and returns the `PropertyResult` without
  ## raising (I3). The property name defaults to the machine name.
  mixin stateMachineRunner, stateMachineKey
  runStateMachine(stateMachineRunner(machine), settings, $machine, stateMachineKey(machine))
