## Stateful (model-based) testing (ADR-0011).
##
## `stateMachine` describes a model, a system under test built fresh for each
## sequence, and commands. The macro generates, at module level:
##
## - `<Name>`: a marker type naming the machine;
## - `<Name>Step` / `<Name>StepKind`: one step as a value (command + arguments);
## - one constructor per command, overloaded on the marker type
##   (`push(BoundedQueue, 3)`), used by `replayCommands`;
## - `stateMachineRunner(<Name>)`: a closure that runs one sequence, either
##   generated from a `ChoiceSource` or replayed from given steps.
##
## The commands are inlined in a single `case` inside that closure: no
## dynamic dispatch, and argument generators that do not read the model or
## the system are built once per property, not per step.

import std/[macros, os, strutils]
import choices, gen, assertions, engine, labels, mining, prng

type
  StateRunner*[S] = proc(src: ChoiceSource; steps: seq[S]; replay: bool;
                         maxSteps: int; swarm: bool) {.closure.}
    ## Runs one sequence. Generated by `stateMachine`; see `stateMachineRunner`.
    ## In replay mode `src` is not used and may be nil.

proc raisePrecondition*(index: int; step: string) {.noinline.} =
  raise newException(ValueError, "replayCommands: precondition of step " & $index &
    " (" & step & ") is false, so this sequence cannot happen")

proc runStateMachine*[S](runner: StateRunner[S]; settings: Settings;
                         machine: string; dbKey = ""): PropertyResult =
  ## Runs random command sequences with the engine of `forAll`.
  var s = settings
  let key = if s.name.len > 0: s.name else: dbKey
  if s.name.len == 0: s.name = machine
  let maxSteps = s.maxSteps
  let swarm = s.swarm
  let noSteps: seq[S] = @[]
  let prop: PropertyProc = proc(src: ChoiceSource) =
    runner(src, noSteps, false, maxSteps, swarm)
  result = runProperty(prop, s, key)
  # Commands that never ran: the model was never exercised there (O4).
  for st in result.labels:
    if st.kind == lkCommand and st.cases == 0 and result.labeledCases > 0:
      var line = "command '" & st.name & "' never ran in " & $result.labeledCases & " sequences"
      for d in result.labels:
        if d.kind == lkDisabled and d.name == st.name:
          line.add "; its precondition was false " & $d.events & " times"
      result.warnings.add line

proc replaySteps*[S](runner: StateRunner[S]; steps: seq[S]) =
  ## Runs `steps` in order with the machine's setup, preconditions,
  ## postconditions, invariants and teardown. Raises on the first failure.
  # No ChoiceSource in replay mode (the runner never touches it): ARC in
  # Nim 2.2.4 leaks a ref created here when the runner raises.
  runner(nil, steps, true, steps.len, false)

# ------------------------------------------------------------------- parsing

type
  Arg = object
    name, source: NimNode
    hoisted: bool

  Command = object
    name: NimNode
    args: seq[Arg]
    precondition, run, postcondition, update: NimNode

  Machine = object
    name, model: NimNode
    setup, teardown, invariant: NimNode
    commands: seq[Command]

proc sectionName(n: NimNode): string =
  ## `name: body` parses as a call of `name` with a statement list.
  if n.kind in {nnkCall, nnkCommand} and n.len == 2 and n[0].kind == nnkIdent and
     n[1].kind == nnkStmtList:
    result = $n[0]

proc mentions(n: NimNode; names: openArray[string]): bool =
  if n.kind == nnkIdent:
    for x in names:
      if n.eqIdent(x): return true
  for c in n:
    if mentions(c, names): return true

proc declaredNames(setup: NimNode): seq[string] =
  for s in setup:
    if s.kind in {nnkLetSection, nnkVarSection, nnkConstSection}:
      for d in s:
        for i in 0 ..< d.len - 2:
          var n = d[i]
          if n.kind == nnkPragmaExpr: n = n[0]
          if n.kind == nnkPostfix: n = n[1]
          if n.kind == nnkIdent: result.add $n

proc parseCommand(n: NimNode; stateNames: seq[string]): Command =
  let sig = n[1]
  if sig.kind == nnkObjConstr:
    # `put(x: int)`: every argument `name: T` makes Nim parse an object
    # constructor (see ADR-0010).
    error("declare command arguments as `name in Type` or `name in generator`", sig)
  if sig.kind notin {nnkCall, nnkIdent, nnkSym, nnkOpenSymChoice, nnkClosedSymChoice} or
     n.len != 3 or n[2].kind != nnkStmtList:
    error("expected `command name(x in source, ...):` followed by its sections", n)
  if sig.kind != nnkCall:
    result.name = sig
  else:
    result.name = sig[0]
    for i in 1 ..< sig.len:
      let a = sig[i]
      if not (a.kind == nnkInfix and a[0].eqIdent("in") and a[1].kind == nnkIdent):
        error("declare command arguments as `name in Type` or `name in generator`", a)
      result.args.add Arg(name: a[1], source: a[2],
                          hoisted: not mentions(a[2], stateNames))
  # In a template, a command named like an existing proc (`reset`) arrives
  # as a symbol: only its name matters here.
  case result.name.kind
  of nnkSym: result.name = ident(result.name.strVal)
  of nnkOpenSymChoice, nnkClosedSymChoice: result.name = ident(result.name[0].strVal)
  else: discard
  if result.name.kind != nnkIdent:
    error("a command name must be an identifier", result.name)
  for s in n[2]:
    case sectionName(s)
    of "precondition": result.precondition = s[1]
    of "run": result.run = s[1]
    of "postcondition": result.postcondition = s[1]
    of "update": result.update = s[1]
    else:
      error("unknown command section; expected precondition:, run:, postcondition: " &
            "or update:", s)
  if result.run.isNil:
    error("command '" & $result.name & "' needs a `run:` section", n)

proc parseMachine(name, body: NimNode): Machine =
  if name.kind != nnkIdent:
    error("expected `stateMachine Name:`", name)
  result.name = name
  result.setup = newStmtList()
  result.teardown = newStmtList()
  result.invariant = newStmtList()
  var commandNodes: seq[NimNode]
  for s in body:
    if s.kind == nnkCommand and s.len >= 2 and s[0].eqIdent("command"):
      commandNodes.add s
      continue
    case sectionName(s)
    of "model": result.model = s[1]
    of "setup":
      for c in s[1]: result.setup.add c
    of "teardown":
      for c in s[1]: result.teardown.add c
    of "invariant":
      for c in s[1]: result.invariant.add c
    else:
      if s.kind == nnkCommentStmt: continue
      error("unknown stateMachine section; expected model:, setup:, teardown:, " &
            "invariant: or command name(...):", s)
  if result.model.isNil:
    error("stateMachine needs a `model:` section (use `model: ()` when there is none)", body)
  if commandNodes.len == 0:
    error("stateMachine needs at least one command", body)
  if commandNodes.len > 255:
    error("stateMachine supports at most 255 commands", body)
  let stateNames = @["model"] & declaredNames(result.setup)
  for c in commandNodes:
    let cmd = parseCommand(c, stateNames)
    for other in result.commands:
      if other.name.eqIdent(cmd.name):
        error("duplicate command '" & $cmd.name & "'", c)
    result.commands.add cmd

